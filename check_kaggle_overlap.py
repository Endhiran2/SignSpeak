"""Compare the 250 Kaggle ASL Signs glosses with our vocabulary.
Run:  python check_kaggle_overlap.py sign_to_prediction_index_map.json
"""
import json, sys
OURS = """ME YOU HE SHE WE THEY MY YOUR NAME WHAT WHERE WHEN WHY HOW WHO
WHICH GO COME WALK RUN SIT STAND STOP START FINISH WAIT LIKE LOVE NEED WANT
HAVE KNOW THINK UNDERSTAND LEARN TEACH READ WRITE WORK PLAY SLEEP WAKE LIVE BUY SELL
GIVE TAKE MEET SEE LOOK HEAR LISTEN TALK TELL ASK ANSWER CALL SHOW EAT DRINK
WATER FOOD MILK COFFEE BREAD APPLE PIZZA BREAKFAST LUNCH DINNER HOME HOUSE SCHOOL STORE HOSPITAL
CHURCH CITY BATHROOM KITCHEN ROOM MOTHER FATHER SISTER BROTHER FAMILY BABY BOY GIRL WOMAN MAN
FRIEND TEACHER DOCTOR STUDENT GOOD BAD HAPPY SAD ANGRY TIRED SICK HUNGRY BIG SMALL HOT
COLD NEW OLD TODAY TOMORROW YESTERDAY NOW MORNING NIGHT WEEK MONTH YEAR TIME WEATHER MORE
FINISH ALL SAME DIFFERENT AGAIN ALWAYS NEVER MAYBE THANKYOU WELCOME EXCUSE FINE CAR BUS TRAIN
PHONE COMPUTER BOOK MONEY CLOTHES SHOE DOG CAT ONE TWO THREE FOUR FIVE SIX SEVEN
EIGHT NINE TEN RED BLUE GREEN YELLOW BLACK WHITE HELP PLEASE SORRY HELLO GOODBYE YES
NO""".split()
ours = set(OURS)
kag = {k.upper().replace(" ", "").replace("-", "") for k in json.load(open(sys.argv[1]))}
overlap = sorted(ours & kag)
print(f"Kaggle signs: {len(kag)} | our words: {len(ours)} | overlap: {len(overlap)}")
print("\nOverlapping words:")
print(" ".join(overlap))
print("\nOur words NOT in Kaggle:")
print(" ".join(sorted(ours - kag)))
print("\nKaggle signs we do not have:")
print(" ".join(sorted(kag - ours)))
